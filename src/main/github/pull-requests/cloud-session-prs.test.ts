import { beforeEach, describe, expect, it, vi } from 'vitest'

type GhApi = (repoPath: string, ownerRepo: unknown, args: string[]) => Promise<string>
const gh = vi.hoisted(() => ({
  calls: [] as string[][],
  answer: (async () => '') as GhApi
}))

vi.mock('./pr-merge-queue-github', () => ({
  ghApi: (repoPath: string, ownerRepo: unknown, args: string[]) => {
    gh.calls.push(args)
    return gh.answer(repoPath, ownerRepo, args)
  }
}))
vi.mock('../repositories/github-api-repository', () => ({
  resolveGitHubRepoExecution: async () => ({ ownerRepo: { owner: 'acme', repo: 'board' } })
}))

const { readAgentBrief } = await import('./cloud-session-prs')

const BRIEF = '> *This was generated by AI during triage.*\n\n## Agent Brief\n\n**Summary:** CSV'

function line(body: string, createdAt: string): string {
  return JSON.stringify({ body, createdAt })
}

describe('readAgentBrief', () => {
  beforeEach(() => {
    gh.calls = []
  })

  it('reads every page of the issue comments and returns the latest agent brief', async () => {
    const comments = [
      line('First!', '2026-01-01T00:00:00Z'),
      line(BRIEF, '2026-01-02T00:00:00Z'),
      line('Thanks', '2026-01-03T00:00:00Z')
    ]
    gh.answer = async () => `${comments.join('\n')}\n`
    await expect(readAgentBrief('/repo', 12)).resolves.toBe(BRIEF)
    expect(gh.calls[0][0]).toBe('repos/acme/board/issues/12/comments?per_page=100')
    expect(gh.calls[0]).toContain('--paginate')
  })

  it('returns null when no comment is an agent brief', async () => {
    gh.answer = async () => line('First!', '2026-01-01T00:00:00Z')
    await expect(readAgentBrief('/repo', 12)).resolves.toBeNull()
  })

  it('returns null instead of failing when the comments cannot be read', async () => {
    gh.answer = async () => {
      throw new Error('HTTP 502')
    }
    await expect(readAgentBrief('/repo', 12)).resolves.toBeNull()
  })
})
