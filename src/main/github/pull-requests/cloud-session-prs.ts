import { z } from 'zod'
import type { GitHubRepositoryIdentity } from '../../../shared/github/repositories/repository-identity'
import { resolveGitHubRepoExecution } from '../repositories/github-api-repository'
import { ghApi } from './pr-merge-queue-github'

const SESSION_LINK = /https:\/\/claude\.ai\/code\/(session_[A-Za-z0-9]+)/
// The footer a Claude cloud session appends to the PRs it opens.
const SESSION_FOOTER =
  /\s*(?:\n-{3,}\s*)?\n_?Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\/session_[A-Za-z0-9]+[^)]*\)_?\s*$/

const OpenPRs = z.array(
  z.object({
    number: z.number(),
    url: z.string(),
    branch: z.string(),
    body: z.string(),
    draft: z.boolean(),
    sameRepo: z.boolean()
  })
)

const IssueSummary = z.object({ title: z.string(), url: z.string() })

export type CloudSessionPR = {
  number: number
  url: string
  branch: string
  body: string
  sessionId: string
}

/** Open, non-draft PRs of the repo's own branches whose body links the cloud session that opened them. */
export async function listOpenCloudSessionPRs(
  repoPath: string
): Promise<{ ownerRepo: GitHubRepositoryIdentity; prs: CloudSessionPR[] }> {
  const { ownerRepo } = await resolveGitHubRepoExecution(repoPath, null)
  if (!ownerRepo) {
    throw new Error('Could not resolve the GitHub repository.')
  }
  const stdout = await ghApi(repoPath, ownerRepo, [
    `repos/${ownerRepo.owner}/${ownerRepo.repo}/pulls?state=open&per_page=100`,
    '--jq',
    '[.[] | {number, url: .html_url, branch: .head.ref, body: (.body // ""), draft, sameRepo: (.head.repo.full_name == .base.repo.full_name)}]'
  ])
  const prs = OpenPRs.parse(JSON.parse(stdout || '[]')).flatMap((pr) => {
    const sessionId = SESSION_LINK.exec(pr.body)?.[1]
    return sessionId && !pr.draft && pr.sameRepo
      ? [{ number: pr.number, url: pr.url, branch: pr.branch, body: pr.body, sessionId }]
      : []
  })
  return { ownerRepo, prs }
}

export async function readIssueSummary(
  repoPath: string,
  ownerRepo: GitHubRepositoryIdentity,
  issueNumber: number
): Promise<{ title: string; url: string }> {
  const stdout = await ghApi(repoPath, ownerRepo, [
    `repos/${ownerRepo.owner}/${ownerRepo.repo}/issues/${issueNumber}`,
    '--jq',
    '{title, url: .html_url}'
  ])
  return IssueSummary.parse(JSON.parse(stdout))
}

/** Drops the session footer, which is Claude attribution, from the PR body; the session id is read first. */
export async function removeCloudSessionFooter(
  repoPath: string,
  ownerRepo: GitHubRepositoryIdentity,
  pr: Pick<CloudSessionPR, 'number' | 'body'>
): Promise<void> {
  const body = pr.body.replace(SESSION_FOOTER, '\n')
  if (body === pr.body) {
    return
  }
  await ghApi(repoPath, ownerRepo, [
    '-X',
    'PATCH',
    `repos/${ownerRepo.owner}/${ownerRepo.repo}/pulls/${pr.number}`,
    '-f',
    `body=${body}`
  ])
}
