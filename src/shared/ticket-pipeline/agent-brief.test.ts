import { describe, expect, it } from 'vitest'
import { findAgentBrief } from './agent-brief'

const DISCLAIMER = '> *This was generated by AI during triage.*'

function brief(summary: string): string {
  return [
    DISCLAIMER,
    '',
    '## Agent Brief',
    '',
    '**Category:** enhancement',
    `**Summary:** ${summary}`
  ].join('\n')
}

describe('findAgentBrief', () => {
  it('finds nothing in no comments', () => {
    expect(findAgentBrief([])).toBeNull()
  })

  it('finds nothing among comments without the heading', () => {
    expect(
      findAgentBrief([
        { body: 'Looks good to me.', createdAt: '2026-01-01T00:00:00Z' },
        { body: 'We should brief the agent on this.', createdAt: '2026-01-02T00:00:00Z' }
      ])
    ).toBeNull()
  })

  it('finds the heading after the triage disclaimer', () => {
    const body = brief('Export the board')
    expect(findAgentBrief([{ body, createdAt: '2026-01-01T00:00:00Z' }])).toBe(body)
  })

  it('takes the latest brief by creation time, whatever the order', () => {
    const older = brief('first take')
    const newer = brief('revised')
    expect(
      findAgentBrief([
        { body: newer, createdAt: '2026-01-03T00:00:00Z' },
        { body: 'A reply after the brief.', createdAt: '2026-01-04T00:00:00Z' },
        { body: older, createdAt: '2026-01-01T00:00:00Z' }
      ])
    ).toBe(newer)
  })

  it('ignores headings that only look like it', () => {
    const lookalikes = [
      '### Agent Brief',
      '## Agent Briefing',
      'See the ## Agent Brief below',
      '## agent brief'
    ]
    expect(
      findAgentBrief(lookalikes.map((body) => ({ body, createdAt: '2026-01-01T00:00:00Z' })))
    ).toBeNull()
  })

  it('accepts trailing whitespace and CRLF line ends on the heading', () => {
    const body = `${DISCLAIMER}\r\n\r\n## Agent Brief  \r\n**Summary:** x`
    expect(findAgentBrief([{ body, createdAt: '2026-01-01T00:00:00Z' }])).toBe(body)
  })

  it('ignores the heading inside a code fence, such as a quoted template', () => {
    const body = ['The template looks like this:', '```markdown', '## Agent Brief', '```'].join(
      '\n'
    )
    expect(findAgentBrief([{ body, createdAt: '2026-01-01T00:00:00Z' }])).toBeNull()
  })
})
