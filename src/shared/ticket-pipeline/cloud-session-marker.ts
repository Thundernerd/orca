/** Which Claude cloud session opened a PR, and which Corka host follows it (null: none yet). */
export type CloudSessionTag = { sessionId: string; host: string | null }

const MARKER = /\n*<!-- corka-cloud session=(session_[A-Za-z0-9]+) host=([A-Za-z0-9-]+) -->\s*/
const SESSION_LINK = /https:\/\/claude\.ai\/code\/(session_[A-Za-z0-9]+)/
// The footer a Claude cloud session appends to the PRs it opens.
const SESSION_FOOTER =
  /\s*(?:\n-{3,}\s*)?\n_?Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\/session_[A-Za-z0-9]+[^)]*\)_?\s*$/

/** The marker a host leaves once it follows the PR, else the session's own footer link. */
export function readCloudSessionTag(body: string): CloudSessionTag | null {
  const marker = MARKER.exec(body)
  if (marker) {
    return { sessionId: marker[1], host: marker[2] }
  }
  const link = SESSION_LINK.exec(body)
  return link ? { sessionId: link[1], host: null } : null
}

/** The body as the agent wrote it, without the footer or Corka's marker. */
export function cloudSessionBodyText(body: string): string {
  return body.replace(MARKER, '\n').replace(SESSION_FOOTER, '\n')
}

/** Swaps the footer, which is Claude attribution, for a hidden marker naming the session and the
 *  host that follows the PR, so every host still recognises it and only that one acts on it. */
export function withCloudSessionMarker(
  body: string,
  tag: { sessionId: string; host: string }
): string {
  return `${cloudSessionBodyText(body).trimEnd()}\n\n<!-- corka-cloud session=${tag.sessionId} host=${tag.host} -->\n`
}
