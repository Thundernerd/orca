import { describe, expect, it } from 'vitest'
import { renderCloudTicketBrief, type CloudTicketBriefInput } from './ticket-cloud-brief'

const input: CloudTicketBriefInput = {
  ticket: { id: '#12', title: 'Add export' },
  ticketBody: 'Export the board as CSV.\n',
  reviewRule: "with 'Closes #12' in the body",
  branch: 'feat/12-add-export',
  baseBranch: 'main',
  agentDocs: ['AGENTS.md']
}

describe('renderCloudTicketBrief', () => {
  it('without an agent brief, renders the brief it always did', () => {
    expect(renderCloudTicketBrief(input)).toMatchInlineSnapshot(`
      "Implement ticket #12 (Add export) on a new branch named exactly \`feat/12-add-export\`, created from origin/main.
      The ticket's text is below; it is the spec. Read AGENTS.md and any references the ticket lists.
      - Proof: if the ticket changes something that can be seen (a page, a command's output) and you can capture it here, capture the before now, before you change anything.
      - Use the /tdd skill. The ticket's "Seams under test" are agreed: build on them without asking. Work in vertical red→green slices.
      - Run the type checker and the single test file you are working on as you go, and the full test suite once at the end.
      - When the acceptance criteria are met and the repo's checks pass, run /code-review with fixed point origin/main and the ticket as the spec. Fix what it finds, or leave it with a reason, or raise it as a finding when it is one (below).
      - Findings: a finding is a real problem outside this ticket's scope: a bug, or a gap in behaviour, tests or docs. Problems in code this branch adds or changes are in scope: fix them here, however small, instead of handing them over. These are not findings, so hand none of them over and say in your report why you left each: a /code-review point you judged not worth fixing; a refactor or tidy-up with no bug behind it; a further pass over code a recent ticket already reworked.
        Related to this ticket and small: fix it here, as its own commit. Otherwise do not fix it: list it under a \`## Findings\` heading in the PR body, one \`### <title>\` per finding with its body below it, using \`####\` headings for the body's parts (the section ends at the next \`##\` heading), and a line \`Blocked by: #12\` when it builds on code only on this branch. Write each in the ticket format (Goal, Scope, Seams under test, Acceptance criteria), citing file:line as the code stands on origin/main. Corka checks each against origin/main and the open tickets and files only the new ones.
      - Write commit messages in Conventional Commits style; commits and the PR body carry no Claude attribution or Co-Authored-By lines.
      - When every fix is committed, push the branch and open a PR to main, writing its body with /pr, with 'Closes #12' in the body. Put the proof in its Evidence: the before, the after on this branch, and the test runs that show it. Do not merge it: Corka's merge queue merges it.
      - If you are blocked (a missing dependency, a spec you cannot resolve) or a decision needs the user, say so in this session and stop instead of guessing.
      - Once the PR is up, report the PR URL, each finding you listed, and each point you left, with why.

      The ticket:

      ---

      Export the board as CSV."
    `)
  })

  it('with no agent brief, or an empty one, renders the same brief', () => {
    const plain = renderCloudTicketBrief(input)
    expect(renderCloudTicketBrief({ ...input, agentBrief: null })).toBe(plain)
    expect(renderCloudTicketBrief({ ...input, agentBrief: '  \n' })).toBe(plain)
  })

  it('carries the agent brief after the ticket, as the spec that wins over the ticket', () => {
    const agentBrief =
      '> *This was generated by AI during triage.*\n\n## Agent Brief\n\n**Summary:** CSV only\n'
    const lines = renderCloudTicketBrief({ ...input, agentBrief }).split('\n')
    expect(lines[1]).toBe(
      "The ticket's text and its agent brief are below; the agent brief is the spec and wins over the ticket's text where they differ, which is context. Read AGENTS.md and any references the ticket lists."
    )
    const ticket = lines.indexOf('Export the board as CSV.')
    const heading = lines.indexOf(
      "The agent brief (the spec; it wins over the ticket's text where they differ):"
    )
    expect(ticket).toBeGreaterThan(-1)
    expect(heading).toBeGreaterThan(ticket)
    expect(lines.slice(heading + 2).join('\n')).toBe(agentBrief.trim())
  })
})
